"""Build results/summary.md from the saved benchmark JSON files. Run from the repo root: python results/summarize.py

Every number comes from the files in results/. Nothing here calls a model or spends money.
Scores are the per-run count of correct tasks out of 6 (hard tier, tests and manifest required).
"""
import json
from pathlib import Path

CONFIGS = [
    # (label, cap, [files])
    ("gemini-4-argon", "4,000", ["gemini-4-argon-hard-probe.json", "gemini-4-argon-hard-probe2.json"]),
    ("gpt-5.6-sol", "4,000", ["gpt-5.6-sol-hard-probe.json", "gpt-5.6-sol-hard-probe2.json"]),
    ("claude-opus-5", "4,000", ["claude-opus-5-hard-probe.json", "claude-opus-5-hard-probe2.json"]),
    ("kimi-k2.7-code", "12,000", ["kimi-k2.7-code-hard-v3-12k.json"]),
    ("minimax-m3", "12,000", ["minimax-m3-hard-v3-12k.json"]),
    ("deepseek-v4-pro", "12,000", ["deepseek-v4-pro-hard-v3-12k.json"]),
    ("qwen3-coder", "12,000", ["qwen3-coder-hard-v3-12k.json"]),
    ("kimi-k2.7-code", "4,000", ["kimi-k2.7-code-hard-new.json", "kimi-k2.7-code-hard-v2.json"]),
    ("minimax-m3", "4,000", ["minimax-m3-hard-new.json", "minimax-m3-hard-v2.json"]),
    ("deepseek-v4-pro", "4,000", ["deepseek-v4-pro-hard-new.json", "deepseek-v4-pro-hard-v2.json"]),
    ("qwen3-coder", "4,000", ["qwen3-coder-hard-new.json", "qwen3-coder-hard-v2.json"]),
]


def runs_of(path: Path) -> list[list[dict]]:
    d = json.loads(path.read_text())
    return d["runs"] if "runs" in d else [d["results"]]


def main() -> None:
    here = Path(__file__).parent
    lines = [
        "# Results summary",
        "",
        "Hard tier (6 tasks), forger-written tests and a capability manifest required, rubber-stamp reviewer (`--auto-approve`), one run = 6 tasks.",
        "Generated by `python results/summarize.py` from the JSON files in this folder. **Spend is not in this table**: the router's own estimates",
        "undercounted badly (see the project notes), so use the provider dashboard for real cost.",
        "",
        "| Model | Reply cap (tokens) | Runs | Mean score (of 6) | Range | Hidden set | Survival | Forge attempts per task | Task errors | Forger reply failures |",
        "|---|---|---|---|---|---|---|---|---|---|",
    ]
    for label, cap, files in CONFIGS:
        runs = [run for f in files for run in runs_of(here / f)]
        scores = [sum(r["correct"] for r in run) for run in runs]
        results = [r for run in runs for r in run]
        hp, ht = sum(r.get("hidden_passed", 0) for r in results), sum(r.get("hidden_total", 0) for r in results)
        sp, st = sum(r.get("survival_passed", 0) for r in results), sum(r.get("survival_total", 0) for r in results)
        attempts = sum(r["forge_attempts"] for r in results)
        errors = sum(r["status"] == "error" for r in results)
        forger_fail = sum(1 for r in results for f in r["failures"] if f.startswith("forger:")) + sum(
            1 for r in results if r["status"] == "error" and "RouterError" in (r["error"] or "")
        )
        lines.append(
            f"| {label} | {cap} | {len(runs)} | {sum(scores) / len(scores):.1f} | {min(scores)} to {max(scores)} | "
            f"{hp}/{ht} | {sp}/{st} | {attempts / len(results):.2f} | {errors} | {forger_fail} |"
        )
    lines += [
        "",
        "Notes:",
        "- Closed-weight models have 3 runs each (1 + 2), open-weight models 3 runs at the 12,000 cap and 6 runs at the 4,000 cap.",
        "- The hidden set and survival counts only cover tasks where a tool was registered (and, for survival, was right first), so denominators differ.",
        "- `Forger reply failures` counts forge attempts that never produced a usable draft (empty reply, invalid JSON, malformed tests).",
        "- `minimax-m3-hard-first-attempt-harness-flaw.*` is a first attempt scored with a harness flaw (test fixtures hidden by the manifest). It is kept as a record and is not in this table.",
        "- Scores are from small samples. Treat them as a direction.",
    ]
    (here / "summary.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
